/**
 * refresh-schema.ts
 *
 * Fetches the GAM Report API proto from GitHub and generates src/schema.ts
 * with the canonical Metric and Dimension enum values from the REST API v1.
 *
 * Usage:
 *   npx tsx scripts/refresh-schema.ts
 *
 * No credentials required — reads the public proto file only.
 */

const PROTO_URL =
  'https://raw.githubusercontent.com/googleapis/googleapis/master/google/ads/admanager/v1/report_definition.proto';

async function main(): Promise<void> {
  process.stderr.write(`Fetching proto from ${PROTO_URL}\n`);
  const res = await fetch(PROTO_URL);
  if (!res.ok) {
    process.stderr.write(`Failed to fetch proto: ${res.status} ${res.statusText}\n`);
    process.exit(1);
  }
  const proto = await res.text();

  const metrics = extractEnum(proto, 'Metric');
  const dimensions = extractEnum(proto, 'Dimension');

  if (metrics.length === 0 || dimensions.length === 0) {
    process.stderr.write('Failed to extract enum values — proto format may have changed.\n');
    process.exit(1);
  }

  const dimDefs = dimensions.map(({ name, comment }) => ({
    name,
    type: guessDimType(name),
    description: comment || `${name} dimension.`,
  }));

  const metricDefs = metrics.map(({ name, comment }) => ({
    name,
    type: guessMetricType(name),
    description: comment || `${name} metric.`,
  }));

  const schemaSource = buildSchemaSource(dimDefs, metricDefs);
  process.stdout.write(schemaSource);
  process.stderr.write(
    `Generated schema: ${dimDefs.length} dimensions, ${metricDefs.length} metrics.\n` +
    `Pipe to src/schema.ts or review before applying.\n`,
  );
}

interface EnumEntry { name: string; comment: string }

/**
 * Extract all non-UNSPECIFIED enum entries from a named enum block in a proto file.
 * Captures the preceding single-line comment (// ...) as the description.
 */
function extractEnum(proto: string, enumName: string): EnumEntry[] {
  // Match the entire enum block
  const enumRe = new RegExp(`enum\\s+${enumName}\\s*\\{([^}]+)\\}`, 's');
  const match = proto.match(enumRe);
  if (!match) return [];

  const body = match[1];
  const lines = body.split('\n');
  const entries: EnumEntry[] = [];
  let pendingComment = '';

  for (const raw of lines) {
    const line = raw.trim();
    if (line.startsWith('//')) {
      pendingComment = line.replace(/^\/\/\s*/, '');
      continue;
    }
    // Match: NAME = NUMBER;
    const entryMatch = line.match(/^([A-Z][A-Z0-9_]+)\s*=\s*\d+\s*;/);
    if (entryMatch) {
      const name = entryMatch[1];
      if (!name.endsWith('_UNSPECIFIED')) {
        entries.push({ name, comment: pendingComment });
      }
      pendingComment = '';
    } else {
      pendingComment = '';
    }
  }
  return entries;
}

function guessDimType(name: string): 'string' | 'number' | 'date' {
  if (/\b(DATE|WEEK|MONTH|HOUR)\b/.test(name)) return 'date';
  if (/\bID\b/.test(name)) return 'number';
  return 'string';
}

function guessMetricType(name: string): 'number' | 'currency' | 'rate' {
  if (/REVENUE|CPM|CPC/.test(name)) return 'currency';
  if (/RATE|CTR|RATIO/.test(name)) return 'rate';
  return 'number';
}

function buildSchemaSource(
  dims: { name: string; type: string; description: string }[],
  metrics: { name: string; type: string; description: string }[],
): string {
  const indent = (json: string) => json.replace(/^/gm, '  ').trimStart();
  return [
    `// AUTO-GENERATED by scripts/refresh-schema.ts on ${new Date().toISOString()}`,
    `// Source: ${PROTO_URL}`,
    `// Review changes before committing — types and descriptions may need manual tweaks.`,
    ``,
    `export type DimensionDef = { name: string; type: 'string' | 'number' | 'date'; description: string };`,
    `export type MetricDef    = { name: string; type: 'number' | 'currency' | 'rate'; description: string };`,
    ``,
    `export const GAM_SCHEMA: { dimensions: DimensionDef[]; metrics: MetricDef[] } = {`,
    `  dimensions: ${indent(JSON.stringify(dims, null, 2))},`,
    `  metrics: ${indent(JSON.stringify(metrics, null, 2))},`,
    `};`,
    ``,
    `const DIMS    = new Set(GAM_SCHEMA.dimensions.map((d) => d.name));`,
    `const METRICS = new Set(GAM_SCHEMA.metrics.map((m) => m.name));`,
    ``,
    `export function isValidDimension(name: string): boolean { return DIMS.has(name); }`,
    `export function isValidMetric(name: string): boolean { return METRICS.has(name); }`,
    ``,
    `export function validateCombo(q: { dimensions: string[]; metrics: string[] }): string | null {`,
    `  for (const d of q.dimensions) if (!isValidDimension(d)) return \`Unknown dimension: \${d}\`;`,
    `  for (const m of q.metrics)    if (!isValidMetric(m))    return \`Unknown metric: \${m}\`;`,
    `  return null;`,
    `}`,
    ``,
  ].join('\n');
}

main().catch((e) => {
  process.stderr.write(`refresh-schema: ${e instanceof Error ? e.stack : String(e)}\n`);
  process.exit(1);
});

