import { writeFileSync } from 'node:fs';
import { createGoogleAuth, createAuthFetch } from '../src/auth.js';

async function main(): Promise<void> {
  const networkCode = process.env.GAM_NETWORK_CODE;
  const keyFile = process.env.GAM_SERVICE_ACCOUNT_KEY_FILE;
  if (!networkCode || !keyFile) {
    process.stderr.write('Set GAM_NETWORK_CODE and GAM_SERVICE_ACCOUNT_KEY_FILE.\n');
    process.exit(2);
  }

  const fetchImpl = createAuthFetch(createGoogleAuth(keyFile));
  const url = `https://admanager.googleapis.com/v1/networks/${networkCode}/reports:fetchReportMetadata`;
  const res = await fetchImpl(url);
  if (!res.ok) {
    process.stderr.write(`fetchReportMetadata ${res.status}: ${await res.text()}\n`);
    process.exit(1);
  }
  const meta = await res.json() as {
    dimensions?: { name: string; type: string; description?: string }[];
    metrics?: { name: string; type: string; description?: string }[];
  };

  const dims = (meta.dimensions ?? []).map((d) => ({
    name: d.name,
    type: mapDimensionType(d.type),
    description: d.description ?? '',
  }));
  const metrics = (meta.metrics ?? []).map((m) => ({
    name: m.name,
    type: mapMetricType(m.type),
    description: m.description ?? '',
  }));

  const fileBody =
    `// AUTO-GENERATED by scripts/refresh-schema.ts on ${new Date().toISOString()}\n` +
    `// Network: ${networkCode}\n\n` +
    `export type DimensionDef = { name: string; type: 'string' | 'number' | 'date'; description: string };\n` +
    `export type MetricDef = { name: string; type: 'number' | 'currency' | 'rate'; description: string };\n\n` +
    `export const GAM_SCHEMA: { dimensions: DimensionDef[]; metrics: MetricDef[] } = {\n` +
    `  dimensions: ${JSON.stringify(dims, null, 2)},\n` +
    `  metrics: ${JSON.stringify(metrics, null, 2)},\n` +
    `};\n\n` +
    `const DIMS = new Set(GAM_SCHEMA.dimensions.map((d) => d.name));\n` +
    `const METRICS = new Set(GAM_SCHEMA.metrics.map((m) => m.name));\n\n` +
    `export function isValidDimension(name: string): boolean { return DIMS.has(name); }\n` +
    `export function isValidMetric(name: string): boolean { return METRICS.has(name); }\n\n` +
    `export function validateCombo(q: { dimensions: string[]; metrics: string[] }): string | null {\n` +
    `  for (const d of q.dimensions) if (!isValidDimension(d)) return \`Unknown dimension: \${d}\`;\n` +
    `  for (const m of q.metrics) if (!isValidMetric(m)) return \`Unknown metric: \${m}\`;\n` +
    `  return null;\n` +
    `}\n`;

  writeFileSync('src/schema.ts', fileBody);
  process.stderr.write(`wrote src/schema.ts: ${dims.length} dims, ${metrics.length} metrics\n`);
}

function mapDimensionType(t: string): 'string' | 'number' | 'date' {
  if (/DATE|WEEK|MONTH|HOUR/.test(t)) return 'date';
  if (/INT|NUMBER|ID/.test(t)) return 'number';
  return 'string';
}
function mapMetricType(t: string): 'number' | 'currency' | 'rate' {
  if (/CURRENCY|REVENUE|COST/.test(t)) return 'currency';
  if (/RATE|RATIO|CTR/.test(t)) return 'rate';
  return 'number';
}

main().catch((e) => { process.stderr.write(`refresh-schema: ${e instanceof Error ? e.stack : String(e)}\n`); process.exit(1); });
